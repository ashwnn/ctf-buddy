<?php
declare(strict_types=1);

/** Shared helpers. The note store is file-backed so the fixture needs no PDO extension. */

const MAX_BODY = 65536;

function json_response(int $status, array $payload): void
{
    http_response_code($status);
    header('Content-Type: application/json');
    header('Cache-Control: no-store');
    echo json_encode($payload, JSON_UNESCAPED_SLASHES), "\n";
    exit;
}

function notes_dir(): string
{
    $dir = getenv('NOTES_DIR') ?: '/data/notes';
    if (!is_dir($dir)) {
        mkdir($dir, 0770, true);
    }
    return rtrim($dir, '/');
}

function files_dir(): string
{
    return rtrim(getenv('FILES_DIR') ?: '/srv/app/files', '/');
}

function note_path(string $id): string
{
    // Ids are generated by this service; anything else is rejected before it
    // reaches the filesystem.
    if (!preg_match('/^[a-f0-9]{32}$/', $id)) {
        json_response(400, ['error' => 'invalid id']);
    }
    return notes_dir() . '/' . $id . '.json';
}

function read_note(string $id): ?array
{
    $path = note_path($id);
    if (!is_file($path)) {
        return null;
    }
    $decoded = json_decode((string) file_get_contents($path), true);
    return is_array($decoded) ? $decoded : null;
}

function write_note(array $note): void
{
    file_put_contents(note_path($note['id']), json_encode($note, JSON_UNESCAPED_SLASHES));
}

function delete_note(string $id): bool
{
    $path = note_path($id);
    if (!is_file($path)) {
        return false;
    }
    return unlink($path);
}
